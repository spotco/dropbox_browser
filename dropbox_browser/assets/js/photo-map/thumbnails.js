import {PHOTO_MAP_THUMBNAIL_CONCURRENCY} from './config.js';
import {runPhotoMapMetadataQueue} from './queue.js';

export function buildPhotoMapThumbnailUrl(sourcePath, mediaKind) {
  var params = new URLSearchParams();
  params.set('path', String(sourcePath || ''));
  params.set('source', 'remote');
  if (String(mediaKind || 'photo') === 'video') {
    return '/video/endpoints/thumbnail?' + params.toString();
  }
  return '/thumbnail?' + params.toString();
}

function pathSet(values) {
  if (values instanceof Set) return values;
  return new Set(Array.isArray(values) ? values.map(String) : []);
}

function metadataForItem(item, metadataResults) {
  if (metadataResults instanceof Map) return metadataResults.get(item.path) || null;
  if (Array.isArray(metadataResults)) {
    return metadataResults.find(function (result) { return result && result.path === item.path; }) || null;
  }
  return null;
}

export function selectPhotoMapThumbnailItems(items, options) {
  var config = options || {};
  var visiblePaths = pathSet(config.visiblePaths);
  var selectedPath = config.selectedPath ? String(config.selectedPath) : '';
  var results = [];
  var seen = new Set();
  (Array.isArray(items) ? items : []).forEach(function (item) {
    var path = String((item && (item.photoMapSourcePath || item.path)) || '');
    var metadata = metadataForItem(item, config.metadataResults);
    var visible = visiblePaths.has(path) || selectedPath === path || item.photoMapVisible === true || item.photoMapSelected === true;
    if (!path || seen.has(path) || !visible || !metadata || metadata.status !== 'located') return;
    var mediaKind = String((metadata.mediaKind || item.photoMapMediaKind) || 'photo');
    if (mediaKind !== 'photo' && mediaKind !== 'video') return;
    seen.add(path);
    results.push(Object.assign({}, item, {
      photoMapThumbnailUrl: buildPhotoMapThumbnailUrl(path, mediaKind),
      photoMapThumbnailKind: mediaKind,
    }));
  });
  return results;
}

export function loadPhotoMapThumbnail(imageFactory, sourcePath, signal, mediaKind) {
  var image = imageFactory();
  var url = buildPhotoMapThumbnailUrl(sourcePath, mediaKind);
  return new Promise(function (resolve, reject) {
    var settled = false;
    function finish(callback, value) {
      if (settled) return;
      settled = true;
      if (signal && typeof signal.removeEventListener === 'function') signal.removeEventListener('abort', abort);
      callback(value);
    }
    function abort() {
      try { image.src = ''; } catch (_error) {}
      var error = new Error('Photo Map thumbnail request aborted.');
      error.name = 'AbortError';
      finish(reject, error);
    }
    image.onload = function () { finish(resolve, {url: url, image: image}); };
    image.onerror = function () { finish(reject, new Error('Photo Map thumbnail request failed.')); };
    if (signal) {
      if (signal.aborted) return abort();
      if (typeof signal.addEventListener === 'function') signal.addEventListener('abort', abort, {once: true});
    }
    image.src = url;
  });
}

export function runPhotoMapThumbnailQueue(items, options) {
  var config = options || {};
  var loader = config.loader;
  if (typeof loader !== 'function') {
    loader = function (item, signal) {
      return loadPhotoMapThumbnail(
        config.imageFactory,
        item.photoMapSourcePath || item.path,
        signal,
        item.mediaKind || item.photoMapMediaKind,
      );
    };
  }
  return runPhotoMapMetadataQueue(items, async function (item, signal) {
    var loaded = await loader(item, signal);
    return Object.assign({}, loaded, {path: item.path, status: 'loaded'});
  }, {
    concurrency: config.concurrency || PHOTO_MAP_THUMBNAIL_CONCURRENCY,
    signal: config.signal,
    isCurrent: config.isCurrent,
    onResult: config.onResult,
  });
}

/*
 * A persistent, browser-owned scheduler for the thumbnail demand generated by
 * Photo Map.  The visible set may change many times while a map is panning;
 * keeping the queue alive lets us remove only stale work instead of aborting
 * every request whenever a new pin is selected.
 */
export function createPhotoMapThumbnailScheduler(options) {
  var config = options || {};
  var concurrency = Number.isInteger(config.concurrency) && config.concurrency > 0
    ? config.concurrency
    : PHOTO_MAP_THUMBNAIL_CONCURRENCY;
  var loader = typeof config.loader === 'function'
    ? config.loader
    : function (item, signal) {
      return loadPhotoMapThumbnail(
        config.imageFactory,
        item.photoMapSourcePath || item.path,
        signal,
        item.mediaKind || item.photoMapMediaKind,
      );
    };
  var onState = typeof config.onState === 'function' ? config.onState : function () {};
  var onResult = typeof config.onResult === 'function' ? config.onResult : function () {};
  var isCurrent = typeof config.isCurrent === 'function' ? config.isCurrent : function () { return true; };
  var desired = new Map();
  var pending = new Map();
  var active = new Map();
  var cache = new Map();
  var failed = new Set();
  var emittedStates = new Map();
  var sequence = 0;
  var running = 0;
  var destroyed = false;
  var demandUpdates = 0;
  var demandNoOpUpdates = 0;
  var lastDemandReason = '';

  function itemPath(item) {
    return String((item && (item.photoMapSourcePath || item.path)) || '');
  }

  function isThumbnailable(item) {
    var kind = String((item && (item.mediaKind || item.photoMapMediaKind)) || 'photo');
    return kind === 'photo' || kind === 'video';
  }

  function isAbort(error, signal) {
    return !!(signal && signal.aborted) || !!(error && error.name === 'AbortError');
  }

  function priorityFor(item, selectedPath, index) {
    var path = itemPath(item);
    var explicitPriority = Number(item && item.photoMapThumbnailPriority);
    if (Number.isFinite(explicitPriority)) return explicitPriority;
    if (path && path === selectedPath) return -1;
    var distance = Number(item && item.photoMapThumbnailDistance);
    return Number.isFinite(distance) ? distance : 1000000 + index;
  }

  function sortPending() {
    var entries = Array.from(pending.values());
    entries.sort(function (left, right) {
      return left.priority - right.priority || left.sequence - right.sequence;
    });
    pending = new Map(entries.map(function (entry) { return [entry.path, entry]; }));
  }

  function emitState(item, state, details) {
    var path = itemPath(item);
    if (destroyed || !isCurrent() || !item || !path) return false;
    var previous = emittedStates.get(path);
    // A successful thumbnail remains ready even if its demand temporarily
    // disappears. Do not emit a visual regression during scheduler churn.
    if (previous === 'ready' && (state === 'idle' || state === 'loading')) return false;
    if (previous === state) return false;
    emittedStates.set(path, state);
    onState(item, state, details || null);
    return true;
  }

  function pump() {
    if (destroyed) return;
    sortPending();
    while (running < concurrency) {
      var next = pending.values().next();
      if (next.done) return;
      var entry = next.value;
      pending.delete(entry.path);
      if (!desired.has(entry.path) || cache.has(entry.path) || failed.has(entry.path)) continue;
      start(entry);
    }
  }

  function start(entry) {
    var controller = typeof AbortController === 'function' ? new AbortController() : {
      signal: undefined,
      abort: function () { this.aborted = true; },
    };
    var record = {
      item: entry.item,
      controller: controller,
      priority: entry.priority,
      sequence: entry.sequence,
      preempted: false,
    };
    active.set(entry.path, record);
    running += 1;
    emitState(entry.item, 'loading', {reason: 'request-started'});
    Promise.resolve().then(function () { return loader(entry.item, controller.signal); }).then(function (loaded) {
      var current = active.get(entry.path) === record;
      if (!current || destroyed || !isCurrent() || !desired.has(entry.path) ||
          (controller.signal && controller.signal.aborted)) return;
      var result = Object.assign({}, loaded, {path: entry.path, status: 'loaded'});
      cache.set(entry.path, result);
      emitState(entry.item, 'ready', {reason: 'request-completed'});
      onResult(entry.item, result);
    }).catch(function (error) {
      var current = active.get(entry.path) === record;
      if (!current || destroyed || !isCurrent() || !desired.has(entry.path)) return;
      if (isAbort(error, controller.signal)) return;
      failed.add(entry.path);
      emitState(entry.item, 'error', {reason: 'thumbnail-load-failure'});
      onResult(entry.item, {
        path: entry.path,
        status: 'error',
        reason: 'thumbnail-load-failure',
      });
    }).finally(function () {
      if (active.get(entry.path) === record) {
        active.delete(entry.path);
        // A higher-priority grouped popup cell displaced this still-desired
        // request. Put it back behind the current demand after its aborted
        // browser image operation has settled.
        if (record.preempted && desired.has(entry.path) && !cache.has(entry.path) && !failed.has(entry.path)) {
          pending.set(entry.path, desired.get(entry.path));
        }
      }
      running = Math.max(0, running - 1);
      pump();
    });
  }

  function preemptLowerPriorityActive(reason) {
    if (!pending.size || !active.size) return;
    sortPending();
    var firstPending = pending.values().next();
    if (firstPending.done) return;
    var highestPendingPriority = firstPending.value.priority;
    active.forEach(function (record) {
      if (record.preempted || record.priority <= highestPendingPriority) return;
      record.preempted = true;
      emitState(record.item, 'idle', {reason: reason || 'priority-preemption'});
      record.controller.abort();
    });
  }

  function removeUndesired(reason) {
    pending.forEach(function (entry, path) {
      if (!desired.has(path)) {
        pending.delete(path);
        emitState(entry.item, 'idle', {reason: reason || 'demand-removed'});
      }
    });
    active.forEach(function (record, path) {
      if (!desired.has(path)) {
        record.controller.abort();
        active.delete(path);
        emitState(record.item, 'idle', {reason: reason || 'demand-removed'});
      }
    });
  }

  function demandEquivalent(left, right) {
    if (!left || !right) return false;
    return left.path === right.path && left.priority === right.priority &&
      itemPath(left.item) === itemPath(right.item) &&
      String(left.item && (left.item.mediaKind || left.item.photoMapMediaKind) || 'photo') ===
        String(right.item && (right.item.mediaKind || right.item.photoMapMediaKind) || 'photo');
  }

  function sameDemand(next) {
    if (next.size !== desired.size) return false;
    for (var pair of next) {
      if (!demandEquivalent(pair[1], desired.get(pair[0]))) return false;
    }
    return true;
  }

  function update(items, options) {
    if (destroyed || !isCurrent()) return {queued: 0, active: active.size, cached: cache.size};
    var updateOptions = options || {};
    var reason = String(updateOptions.reason || 'viewport-refresh');
    var selectedPath = updateOptions.selectedPath ? String(updateOptions.selectedPath) : '';
    var next = new Map();
    (Array.isArray(items) ? items : []).forEach(function (item, index) {
      var path = itemPath(item);
      if (!path || !isThumbnailable(item)) return;
      var candidate = {
        path: path,
        item: Object.assign({}, item, {
          photoMapThumbnailUrl: buildPhotoMapThumbnailUrl(path, item.mediaKind || item.photoMapMediaKind),
          photoMapThumbnailKind: item.mediaKind || item.photoMapMediaKind || 'photo',
        }),
        priority: priorityFor(item, selectedPath, index),
        sequence: sequence++,
      };
      var existing = next.get(path);
      // A group-pin representative may also be visible in its popup grid.
      // Preserve the more urgent of the two demands in the one shared queue.
      if (!existing || candidate.priority < existing.priority) next.set(path, candidate);
    });
    demandUpdates += 1;
    lastDemandReason = reason;
    if (sameDemand(next)) {
      demandNoOpUpdates += 1;
      return {
        queued: pending.size,
        active: active.size,
        cached: cache.size,
        changed: false,
        reason: reason,
      };
    }
    desired = next;
    removeUndesired(reason);
    desired.forEach(function (entry, path) {
      if (cache.has(path) || failed.has(path)) return;
      var activeRecord = active.get(path);
      if (activeRecord) {
        // The same thumbnail can be the ordinary visible group-pin image and
        // then become a high-priority popup cell. Promote that in-flight job
        // rather than aborting and restarting identical browser work.
        if (entry.priority < activeRecord.priority) activeRecord.priority = entry.priority;
        activeRecord.item = entry.item;
        return;
      }
      if (pending.has(path)) {
        pending.set(path, entry);
        return;
      }
      pending.set(path, entry);
    });
    desired.forEach(function (entry, path) {
      if (cache.has(path)) emitState(entry.item, 'ready');
    });
    // If a user opens a grouped popup while ordinary map-pin thumbnails are
    // occupying every slot, abort those lower-priority client-side image
    // requests. Once their aborts settle, pump() immediately starts the
    // currently visible grouped cells and later requeues the displaced pins.
    preemptLowerPriorityActive('priority-preemption');
    pump();
    return {
      queued: pending.size,
      active: active.size,
      cached: cache.size,
      changed: true,
      reason: reason,
    };
  }

  function promote(item) {
    var items = Array.from(desired.values()).map(function (entry) { return entry.item; });
    var path = itemPath(item);
    if (path && !items.some(function (entry) { return itemPath(entry) === path; })) items.push(item);
    return update(items, {selectedPath: path});
  }

  function cancel(reason) {
    desired = new Map();
    removeUndesired(reason || 'scheduler-cancel');
    pending.clear();
  }

  function reset(options) {
    var resetOptions = options || {};
    cancel('scheduler-reset');
    failed.clear();
    if (resetOptions.clearCache !== false) cache.clear();
  }

  return {
    update: update,
    promote: promote,
    cancel: cancel,
    reset: reset,
    getCached: function (path) { return cache.get(String(path || '')) || null; },
    hasPending: function (path) { return pending.has(String(path || '')); },
    getDebugState: function () {
      return {
        desiredPaths: Array.from(desired.keys()),
        pendingPaths: Array.from(pending.keys()),
        activePaths: Array.from(active.keys()),
        cachedPaths: Array.from(cache.keys()),
        failedPaths: Array.from(failed.values()),
        running: running,
        concurrency: concurrency,
        demandUpdates: demandUpdates,
        demandNoOpUpdates: demandNoOpUpdates,
        lastDemandReason: lastDemandReason,
      };
    },
    getActivePaths: function () { return Array.from(active.keys()); },
    getPendingPaths: function () { return Array.from(pending.keys()); },
    destroy: function () {
      destroyed = true;
      cancel();
      cache.clear();
      failed.clear();
    },
  };
}
