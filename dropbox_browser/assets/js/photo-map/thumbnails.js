import {PHOTO_MAP_THUMBNAIL_CONCURRENCY} from './config.js';
import {runPhotoMapMetadataQueue} from './queue.js';

export function buildPhotoMapThumbnailUrl(sourcePath) {
  var params = new URLSearchParams();
  params.set('path', String(sourcePath || ''));
  params.set('source', 'remote');
  return '/thumbnail?' + params.toString();
}

function pathSet(values) {
  if (values instanceof Set) return values;
  return new Set(Array.isArray(values) ? values.map(String) : []);
}

function metadataForItem(item, metadataResults) {
  if (metadataResults instanceof Map) return metadataResults.get(item.path) || null;
  if (Array.isArray(metadataResults)) {
    return metadataResults.find(function (result) { return result && result.path === item.path; }) || null;
  }
  return null;
}

export function selectPhotoMapThumbnailItems(items, options) {
  var config = options || {};
  var visiblePaths = pathSet(config.visiblePaths);
  var selectedPath = config.selectedPath ? String(config.selectedPath) : '';
  var results = [];
  var seen = new Set();
  (Array.isArray(items) ? items : []).forEach(function (item) {
    var path = String((item && (item.photoMapSourcePath || item.path)) || '');
    var metadata = metadataForItem(item, config.metadataResults);
    var visible = visiblePaths.has(path) || selectedPath === path || item.photoMapVisible === true || item.photoMapSelected === true;
    if (!path || seen.has(path) || !visible || !metadata || metadata.status !== 'located') return;
    if ((metadata.mediaKind || item.photoMapMediaKind) !== 'photo') return;
    seen.add(path);
    results.push(Object.assign({}, item, {
      photoMapThumbnailUrl: buildPhotoMapThumbnailUrl(path),
    }));
  });
  return results;
}

export function loadPhotoMapThumbnail(imageFactory, sourcePath, signal) {
  var image = imageFactory();
  var url = buildPhotoMapThumbnailUrl(sourcePath);
  return new Promise(function (resolve, reject) {
    var settled = false;
    function finish(callback, value) {
      if (settled) return;
      settled = true;
      if (signal && typeof signal.removeEventListener === 'function') signal.removeEventListener('abort', abort);
      callback(value);
    }
    function abort() {
      try { image.src = ''; } catch (_error) {}
      var error = new Error('Photo Map thumbnail request aborted.');
      error.name = 'AbortError';
      finish(reject, error);
    }
    image.onload = function () { finish(resolve, {url: url, image: image}); };
    image.onerror = function () { finish(reject, new Error('Photo Map thumbnail request failed.')); };
    if (signal) {
      if (signal.aborted) return abort();
      if (typeof signal.addEventListener === 'function') signal.addEventListener('abort', abort, {once: true});
    }
    image.src = url;
  });
}

export function runPhotoMapThumbnailQueue(items, options) {
  var config = options || {};
  var loader = config.loader;
  if (typeof loader !== 'function') {
    loader = function (item, signal) {
      return loadPhotoMapThumbnail(config.imageFactory, item.photoMapSourcePath || item.path, signal);
    };
  }
  return runPhotoMapMetadataQueue(items, async function (item, signal) {
    var loaded = await loader(item, signal);
    return Object.assign({}, loaded, {path: item.path, status: 'loaded'});
  }, {
    concurrency: config.concurrency || PHOTO_MAP_THUMBNAIL_CONCURRENCY,
    signal: config.signal,
    isCurrent: config.isCurrent,
    onResult: config.onResult,
  });
}

/*
 * A persistent, browser-owned scheduler for the thumbnail demand generated by
 * Photo Map.  The visible set may change many times while a map is panning;
 * keeping the queue alive lets us remove only stale work instead of aborting
 * every request whenever a new pin is selected.
 */
export function createPhotoMapThumbnailScheduler(options) {
  var config = options || {};
  var concurrency = Number.isInteger(config.concurrency) && config.concurrency > 0
    ? config.concurrency
    : PHOTO_MAP_THUMBNAIL_CONCURRENCY;
  var loader = typeof config.loader === 'function'
    ? config.loader
    : function (item, signal) {
      return loadPhotoMapThumbnail(config.imageFactory, item.photoMapSourcePath || item.path, signal);
    };
  var onState = typeof config.onState === 'function' ? config.onState : function () {};
  var onResult = typeof config.onResult === 'function' ? config.onResult : function () {};
  var isCurrent = typeof config.isCurrent === 'function' ? config.isCurrent : function () { return true; };
  var desired = new Map();
  var pending = new Map();
  var active = new Map();
  var cache = new Map();
  var failed = new Set();
  var sequence = 0;
  var running = 0;
  var destroyed = false;

  function itemPath(item) {
    return String((item && (item.photoMapSourcePath || item.path)) || '');
  }

  function isPhoto(item) {
    return String((item && (item.mediaKind || item.photoMapMediaKind)) || 'photo') === 'photo';
  }

  function isAbort(error, signal) {
    return !!(signal && signal.aborted) || !!(error && error.name === 'AbortError');
  }

  function priorityFor(item, selectedPath, index) {
    var path = itemPath(item);
    if (path && path === selectedPath) return -1;
    var distance = Number(item && item.photoMapThumbnailDistance);
    return Number.isFinite(distance) ? distance : 1000000 + index;
  }

  function sortPending() {
    var entries = Array.from(pending.values());
    entries.sort(function (left, right) {
      return left.priority - right.priority || left.sequence - right.sequence;
    });
    pending = new Map(entries.map(function (entry) { return [entry.path, entry]; }));
  }

  function emitState(item, state) {
    if (destroyed || !isCurrent() || !item) return;
    onState(item, state);
  }

  function pump() {
    if (destroyed) return;
    sortPending();
    while (running < concurrency) {
      var next = pending.values().next();
      if (next.done) return;
      var entry = next.value;
      pending.delete(entry.path);
      if (!desired.has(entry.path) || cache.has(entry.path) || failed.has(entry.path)) continue;
      start(entry);
    }
  }

  function start(entry) {
    var controller = typeof AbortController === 'function' ? new AbortController() : {
      signal: undefined,
      abort: function () { this.aborted = true; },
    };
    var record = {item: entry.item, controller: controller, sequence: entry.sequence};
    active.set(entry.path, record);
    running += 1;
    emitState(entry.item, 'loading');
    Promise.resolve().then(function () { return loader(entry.item, controller.signal); }).then(function (loaded) {
      var current = active.get(entry.path) === record;
      if (!current || destroyed || !isCurrent() || !desired.has(entry.path) ||
          (controller.signal && controller.signal.aborted)) return;
      var result = Object.assign({}, loaded, {path: entry.path, status: 'loaded'});
      cache.set(entry.path, result);
      emitState(entry.item, 'ready');
      onResult(entry.item, result);
    }).catch(function (error) {
      var current = active.get(entry.path) === record;
      if (!current || destroyed || !isCurrent() || !desired.has(entry.path)) return;
      if (isAbort(error, controller.signal)) return;
      failed.add(entry.path);
      emitState(entry.item, 'error');
      onResult(entry.item, {
        path: entry.path,
        status: 'error',
        reason: 'thumbnail-load-failure',
      });
    }).finally(function () {
      if (active.get(entry.path) === record) active.delete(entry.path);
      running = Math.max(0, running - 1);
      pump();
    });
  }

  function removeUndesired() {
    pending.forEach(function (entry, path) {
      if (!desired.has(path)) {
        pending.delete(path);
        emitState(entry.item, 'idle');
      }
    });
    active.forEach(function (record, path) {
      if (!desired.has(path)) {
        record.controller.abort();
        active.delete(path);
        emitState(record.item, 'idle');
      }
    });
  }

  function update(items, options) {
    if (destroyed || !isCurrent()) return {queued: 0, active: active.size, cached: cache.size};
    var updateOptions = options || {};
    var selectedPath = updateOptions.selectedPath ? String(updateOptions.selectedPath) : '';
    var next = new Map();
    (Array.isArray(items) ? items : []).forEach(function (item, index) {
      var path = itemPath(item);
      if (!path || !isPhoto(item) || next.has(path)) return;
      next.set(path, {
        path: path,
        item: Object.assign({}, item, {photoMapThumbnailUrl: buildPhotoMapThumbnailUrl(path)}),
        priority: priorityFor(item, selectedPath, index),
        sequence: sequence++,
      });
    });
    desired = next;
    removeUndesired();
    desired.forEach(function (entry, path) {
      if (cache.has(path) || failed.has(path) || active.has(path) || pending.has(path)) return;
      pending.set(path, entry);
    });
    desired.forEach(function (entry, path) {
      if (cache.has(path)) emitState(entry.item, 'ready');
    });
    pump();
    return {
      queued: pending.size,
      active: active.size,
      cached: cache.size,
    };
  }

  function promote(item) {
    var items = Array.from(desired.values()).map(function (entry) { return entry.item; });
    var path = itemPath(item);
    if (path && !items.some(function (entry) { return itemPath(entry) === path; })) items.push(item);
    return update(items, {selectedPath: path});
  }

  function cancel() {
    desired = new Map();
    removeUndesired();
    pending.clear();
  }

  function reset(options) {
    var resetOptions = options || {};
    cancel();
    failed.clear();
    if (resetOptions.clearCache !== false) cache.clear();
  }

  return {
    update: update,
    promote: promote,
    cancel: cancel,
    reset: reset,
    getCached: function (path) { return cache.get(String(path || '')) || null; },
    hasPending: function (path) { return pending.has(String(path || '')); },
    getActivePaths: function () { return Array.from(active.keys()); },
    getPendingPaths: function () { return Array.from(pending.keys()); },
    destroy: function () {
      destroyed = true;
      cancel();
      cache.clear();
      failed.clear();
    },
  };
}
